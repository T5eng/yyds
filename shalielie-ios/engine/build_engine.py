#!/usr/bin/env python3
"""Bundle Shalielie's browser port into one JavaScriptCore/Scriptable engine."""

from __future__ import annotations

import base64
import json
import re
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
VENDOR = HERE / "vendor"
SRC = VENDOR / "src"
PROFILES = VENDOR / "profiles"
IOS_DIR = HERE.parent / "ios" / "PhotographicStylePort"
SHORTCUTS_DIR = HERE.parent / "shortcuts"

MODULES = ["box.js", "bplist.js", "heif.js", "exif.js", "styles.js", "texture.js", "port.js"]

IMPORT_RE = re.compile(r"^import[\s\S]*?from\s+[\"'][^\"']+[\"'];?[ \t]*$", re.M)
EXPORT_BLOCK_RE = re.compile(r"^export\s*\{[^}]*\};?[ \t]*$", re.M)
EXPORT_DECL_RE = re.compile(r"^export\s+(?=(?:const|let|var|function|class|async)\b)", re.M)


def strip_module(text: str) -> str:
    text = IMPORT_RE.sub("", text)
    text = EXPORT_BLOCK_RE.sub("", text)
    text = EXPORT_DECL_RE.sub("", text)
    return text.strip()


def b64(data: bytes) -> str:
    return base64.b64encode(data).decode("ascii")


def embed_profile(zip_path: Path) -> dict:
    with zipfile.ZipFile(zip_path) as zf:
        names = set(zf.namelist())
        manifest = json.loads(zf.read("manifest.json"))
        payloads = {}
        for name in names:
            if name.startswith("payloads/") and name.endswith(".bin"):
                iid = Path(name).stem
                payloads[iid] = b64(zf.read(name))
        return {
            "manifest": manifest,
            "ftyp": b64(zf.read("ftyp.bin")),
            "meta": b64(zf.read("meta.bin")),
            "mn54": b64(zf.read("makernote_0x54.bin")),
            "payloads": payloads,
        }


def js_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def main() -> None:
    core = "\n\n".join(
        f"// ---- {name} ----\n{strip_module((SRC / name).read_text(encoding='utf-8'))}"
        for name in MODULES
    )
    polyfill = (HERE / "polyfill.js").read_text(encoding="utf-8")
    facade = (HERE / "facade.js").read_text(encoding="utf-8")

    index = json.loads((PROFILES / "index.json").read_text(encoding="utf-8"))
    embedded = {}
    profile_index = {}
    for name, info in index.items():
        embedded[name] = embed_profile(PROFILES / info["file"])
        profile_index[name] = {
            "primary_tiles": info["primary_tiles"],
            "hdr_tiles": info["hdr_tiles"],
        }

    profiles_js = (
        "const PROFILE_INDEX = "
        + json.dumps(profile_index, ensure_ascii=False)
        + ";\nconst EMBEDDED_PROFILES = "
        + json.dumps(embedded, ensure_ascii=False)
        + ";\n"
    )

    banner = (
        "/* Photographic Style Port engine\n"
        " * Bundled from nathanatgit/Shalielie (MIT) web/src for iOS Shortcuts / JavaScriptCore.\n"
        " * Generated by engine/build_engine.py — do not edit by hand.\n"
        " */\n"
    )
    engine = "\n\n".join([banner, polyfill, core, profiles_js, facade]) + "\n"

    out = HERE / "engine.js"
    out.write_text(engine, encoding="utf-8")

    IOS_DIR.mkdir(parents=True, exist_ok=True)
    (IOS_DIR / "Engine.js").write_text(engine, encoding="utf-8")

    wrapper = (HERE / "scriptable_wrapper.js").read_text(encoding="utf-8")
    SHORTCUTS_DIR.mkdir(parents=True, exist_ok=True)
    (SHORTCUTS_DIR / "PhotographicStylePort.js").write_text(
        engine + "\n\n" + wrapper, encoding="utf-8"
    )

    print(f"engine.js                    {out.stat().st_size:,} bytes")
    print(f"ios/.../Engine.js            {(IOS_DIR / 'Engine.js').stat().st_size:,} bytes")
    print(f"shortcuts/...Port.js         {(SHORTCUTS_DIR / 'PhotographicStylePort.js').stat().st_size:,} bytes")
    print(f"profiles                     {', '.join(profile_index)}")


if __name__ == "__main__":
    main()
